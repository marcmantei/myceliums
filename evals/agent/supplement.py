#!/usr/bin/env python3
"""Pre-registered supplement of the #182 run (see README, "Pre-registration of the main run").

Two analyses the generated REPORT.md / TOKENS.md do not have, fixed before any
session of arm C or D ran:

* spend per arm and per pair, split into uncached input, cache write, cache
  read and output tokens, with cost and turns (per session and per solved task);
* answer items that never appeared in the session's tool output, per arm and
  category: an indication of what the model answered from memory.

    python3 evals/agent/supplement.py LABEL           # reads runs/<label>, writes results/<label>/unseen.jsonl + SUPPLEMENT.md
    python3 evals/agent/supplement.py LABEL --check   # SUPPLEMENT.md matches the committed data
"""
from __future__ import annotations

import argparse
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from aeval import config  # noqa: E402
from aeval.stats import mean, paired_bootstrap, per_success_bootstrap  # noqa: E402
from aeval.stream import _result_text  # noqa: E402

TOKEN_CLASSES = (("input_tokens", "uncached input"), ("cache_creation_input_tokens", "cache write"),
                 ("cache_read_input_tokens", "cache read"), ("output_tokens", "output"))
MEASURES = (*TOKEN_CLASSES, ("tokens", "all tokens"), ("cost_usd", "USD"), ("num_turns", "turns"))


def tool_output(transcript: Path) -> str:
    """The text of every tool result in a transcript (hook text and the prompt are not tool output)."""
    out = []
    for line in transcript.read_text(encoding="utf-8").splitlines():
        try:
            ev = json.loads(line)
        except ValueError:
            continue
        content = (ev.get("message") or {}).get("content") if ev.get("type") == "user" else None
        for part in content if isinstance(content, list) else []:
            if isinstance(part, dict) and part.get("type") == "tool_result":
                out.append(_result_text(part.get("content")))
    return "\n".join(out)


def _word(w: str, text: str) -> bool:
    return re.search(r"(?<![\w$])" + re.escape(w) + r"(?![\w$])", text) is not None


def seen(item: str, text: str) -> tuple[bool, bool]:
    """(strict, lenient): did the answer item appear in the tool output?

    A path is seen strictly when it appears in full, leniently when its file
    name and its parent directory's name both appear (compact output groups
    files by directory, shell output may be relative to a subdirectory). A
    symbol is seen when each of its last two dot segments appears as a word
    (both measures)."""
    item = re.sub(r"\(.*\)$", "", item.strip())
    if "/" in item:
        path = item.lstrip("./")
        parts = path.split("/")
        strict = path in text
        return strict, strict or (_word(parts[-1], text) and _word(parts[-2], text))
    ok = all(_word(p, text) for p in item.split(".")[-2:] if p)
    return ok, ok


def unseen_rows(label: str, rows: list[dict]) -> list[dict]:
    out = []
    for r in rows:
        path = config.RUNS_DIR / label / "sessions" / r["run_id"] / f"attempt{r['attempt']}.jsonl"
        text = tool_output(path)
        items = list(dict.fromkeys(r.get("answer") or []))
        wrong = set(r.get("false_positives") or [])
        flags = {i: seen(i, text) for i in items}
        out.append({"run_id": r["run_id"], "task_id": r["task_id"], "condition": r["condition"], "rep": r["rep"],
                    "n_items": len(items), "n_correct": sum(i not in wrong for i in items),
                    "unseen_strict": [i for i in items if not flags[i][0]],
                    "unseen_lenient": [i for i in items if not flags[i][1]],
                    "unseen_lenient_correct": [i for i in items if not flags[i][1] and i not in wrong]})
    return out


def _spend(r: dict, key: str) -> float:
    if key == "tokens":
        return (r.get("total_input_tokens") or 0) + (r.get("output_tokens") or 0)
    return float(r.get(key) or 0)


def render(label: str) -> str:
    res = config.RESULTS_DIR / label
    meta = config.load_json(res / "meta.json")
    cat = {t["id"]: t.get("category") or t["type"] for t in config.load_json(res / "tasks_snapshot.json")}
    rows = [json.loads(x) for x in (res / "results.jsonl").read_text().splitlines() if x.strip()]
    unseen = [json.loads(x) for x in (res / "unseen.jsonl").read_text().splitlines() if x.strip()]
    arms = [c for c in meta["conditions"] if any(r["condition"] == c for r in rows)]
    by = defaultdict(lambda: defaultdict(list))
    for r in rows:
        by[r["condition"]][r["task_id"]].append(r)
    L = [f"# Supplement: {label}", "",
         f"Generated by `python3 evals/agent/supplement.py {label}`; the analysis was fixed before any session of "
         "arm C or D ran (pre-registration in [`../../README.md`](../../README.md)).", "",
         "## Spend by token class", "",
         "Per session (mean) and per solved task (sum over the arm's sessions ÷ solved sessions).", "",
         "| Arm | Sessions | Solved | " + " | ".join(n for _, n in MEASURES) + " |",
         "|---|---:|---:|" + "---:|" * len(MEASURES)]

    def fmt(key, v):
        return f"{v:.4f}" if key == "cost_usd" else f"{v:.1f}" if key == "num_turns" else f"{v:,.0f}"

    for c in arms:
        rs = [r for r in rows if r["condition"] == c]
        n_ok = sum(1 for r in rs if r["success"])
        L.append(f"| `{c}` per session | {len(rs)} | {n_ok} | "
                 + " | ".join(fmt(k, mean([_spend(r, k) for r in rs])) for k, _ in MEASURES) + " |")
        L.append(f"| `{c}` per solved task | | | " + " | ".join(
            fmt(k, sum(_spend(r, k) for r in rs) / n_ok) if n_ok else "n/a" for k, _ in MEASURES) + " |")
    L += ["", "## Pairs", "", "Difference per session (first − second, tasks as unit, repetitions averaged) and ratio "
          "per solved task (first ÷ second), each with a 95 % paired bootstrap interval over tasks, not corrected for "
          "multiple comparisons.", "", "| Pair | Measure | Δ per session | Ratio per solved task |", "|---|---|---:|---:|"]
    for i, x in enumerate(arms):
        for y in arms[i + 1:]:
            ids = [t for t in cat if t in by[x] and t in by[y]]
            for key, name in MEASURES:
                d = paired_bootstrap([(mean([_spend(r, key) for r in by[x][t]]),
                                       mean([_spend(r, key) for r in by[y][t]])) for t in ids])
                p = per_success_bootstrap([(sum(_spend(r, key) for r in by[x][t]), sum(bool(r["success"]) for r in by[x][t]),
                                            sum(_spend(r, key) for r in by[y][t]), sum(bool(r["success"]) for r in by[y][t]))
                                           for t in ids])
                L.append(f"| `{x}` vs `{y}` | {name} | {fmt(key, d.diff_mean)} [{fmt(key, d.diff_lo)}, "
                         f"{fmt(key, d.diff_hi)}] | {p['ratio']:.2f}× [{p['ratio_lo']:.2f}×, {p['ratio_hi']:.2f}×] |")
    L += ["", "## Answer items never seen in tool output", "",
          "Spring is very likely in the model's training data. An item counts as unseen when it appears in no tool "
          "result of its session (`seen` in `supplement.py`; *strict*: a path in full; *lenient*: a path's file name and "
          "parent directory). It is a lower bound for answers from memory: an item the agent guessed and then confirmed "
          "with a tool counts as seen, and one it inferred from what it read can count as unseen.", "",
          "| Category | Arm | Answer items | Unseen (strict) | Unseen (lenient) | of them correct |", "|---|---|---:|---:|---:|---:|"]
    for k in [*sorted(set(cat.values())), "all"]:
        for c in arms:
            us = [u for u in unseen if u["condition"] == c and k in ("all", cat[u["task_id"]])]
            n = sum(u["n_items"] for u in us)
            s, le, co = (sum(len(u[f]) for u in us) for f in ("unseen_strict", "unseen_lenient", "unseen_lenient_correct"))
            pct = (lambda v: f"{v} ({100 * v / n:.1f} %)") if n else (lambda v: "0")
            L.append(f"| {k} | `{c}` | {n} | {pct(s)} | {pct(le)} | {co} |")
    return "\n".join(L) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("label")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    res = config.RESULTS_DIR / a.label
    if a.check:
        ok = render(a.label) == (res / "SUPPLEMENT.md").read_text()
        print("SUPPLEMENT.md is current" if ok else "SUPPLEMENT.md differs from the committed data")
        return 0 if ok else 1
    rows = [json.loads(x) for x in (res / "results.jsonl").read_text().splitlines() if x.strip()]
    (res / "unseen.jsonl").write_text("".join(json.dumps(u, sort_keys=True) + "\n" for u in unseen_rows(a.label, rows)))
    (res / "SUPPLEMENT.md").write_text(render(a.label))
    return 0


if __name__ == "__main__":
    sys.exit(main())
